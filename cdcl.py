    def deduce(self):
        """
        实现 BCP (Boolean Constraint Propagation)。
        不断寻找单位子句并进行传播。
        """
        logging.info("Deduce")
        while True:
            found_unit = False
            for c in self.clauses.clauses:
                status, lit = self.is_unit_clause(c)
                if status == "conflict":
                    logging.info("Conflict detected in clause %s" % c)
                    return c # 返回冲突子句
                elif status == "unit":
                    var = abs(lit)
                    value = (lit > 0)
                    logging.info("Unit propagation: %d from clause %s" % (lit, c))
                    self.assignments[var] = value
                    self.trail.append((lit, c, self.decision_level))
                    found_unit = True
                    break  
        
            if not found_unit:
                return None  # 无更多单位子句可传播
        
    def all_assigned(self):
        """
        Returns true if all the literals have been assigned.
        """
        return len(self.assignments) == self.num_vars
    
    #TODO
    def decide(self):
        """
        决策：选择一个新变量并赋值。
        """
        logging.info("Decide a new variable assignment")
        self.decision_level += 1
        for var in range(1, self.num_vars + 1):
            if var not in self.assignments:
                lit = var
                logging.info("Decision: variable %d = True at level %d" % (var, self.decision_level))
                self.assignments[var] = True
                self.trail.append((lit, None, self.decision_level)) # 决策的 reason 为 None
                return
        logging.warning("decide() called but all variables assigned")
    
    def resolve(self, clause1, clause2, lit):
        """
        归结 (Resolution) 两个子句。
        clause1 包含 -lit, clause2 包含 lit。
        """
        result = []
        for l in clause1:
            if l != -lit:
                result.append(l)
        for l in clause2:
            if l != lit and l not in result:
                result.append(l)
        return result

    def _clause_id(self, clause_list):
        """ 查找子句对应的证明 ID """
        key = tuple(sorted(clause_list))
        return self.clauses.content_to_id.get(key, 0)

    def _proof_resolve_step(self, conflict, current_id, lit, reason):
        """ 执行一步归结并记录证明 """
        reason_id  = self._clause_id(reason)
        new_id     = self.clauses.next_id
        self.clauses.next_id += 1
        
        new_clause = self.resolve(conflict, reason, lit)
        
        # 记录到文件
        self.proof.log_step(new_id, lit, current_id, reason_id, new_clause)
        # 注册新子句内容以便后续引用
        self.clauses.content_to_id[tuple(sorted(new_clause))] = new_id
        
        return new_clause, new_id

