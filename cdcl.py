class ClauseDb:
    """
    Store the set of clauses Implement 2-watched literals
    """
    def __init__(self, num_vars, clauses):
        self.clauses = clauses
        # you may want to store the unit clauses
        # and use them only at decision level 0
        self.unit = [] 

        # Map from literal to the clauses containing it
        # This is just a suggestion, you can change this data structure as you wish.
        self.lit2clauses = {}

        # -- Proof ID tables ---------------------------------------------------
        #
        # Two complementary maps so any clause can be looked up cheaply:
        #
        #   clause_id     : id(list_object) -> proof_id
        #     O(1) lookup by Python object identity.
        #     Used when deduce() returns the exact list object.
        #
        #   content_to_id : tuple(sorted(lits)) -> proof_id
        #     Content-based O(1) lookup.
        #     Used when we only have a reason list from the trail (and the
        #     list object identity may differ from the stored clause).
        #
        # Initial clause IDs: 1..n  (DIMACS order)
        # Learned clause IDs: allocated from next_id upward
        self.clause_id     = {}   # {id(list): int}
        self.content_to_id = {}   # {tuple(sorted_lits): int}
        self.next_id       = len(clauses) + 1   # next available proof ID

        # Register all initial clauses with IDs 1..n
        for idx, c in enumerate(clauses):
            pid = idx + 1
            self.clause_id[id(c)]               = pid
            self.content_to_id[tuple(sorted(c))] = pid


