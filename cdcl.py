# =============================================================================
# Proof Infrastructure
# =============================================================================
#
# Proof file format (plain text):
#
#   Header:
#     p proof <n>          -- n = number of initial clauses (IDs 1..n)
#
#   Each resolution step:
#     <new_id> <pivot> <id1> <id2> : <lit1> <lit2> ... 0
#
#   where:
#     new_id  -- ID assigned to the new resolvent clause
#     pivot   -- literal resolved away; id1 contains -pivot, id2 contains +pivot
#     id1     -- ID of parent clause containing -pivot
#     id2     -- ID of parent clause containing +pivot
#     lits 0  -- resolvent literals terminated by 0  ("0" alone = empty clause)
#
# =============================================================================

class ProofLogger:
    """Writes one resolution step per line to a plain-text proof file.

    When proof_file path is given, use a real ProofLogger.
    Otherwise use the lightweight _NullLogger (no-op).
    Two classes let the main logic stay branch-free.
    """

    def __init__(self, proof_file, n_initial):
        self._fh = open(proof_file, 'w', encoding='utf-8')
        # Header: record number of initial clauses so checker can identify them
        # ID 1..n_initial are initial; learned clauses start from n_initial+1
        self._fh.write("c Resolution proof generated by CDCL solver\n")
        self._fh.write("c Initial clause IDs: 1..%d\n" % n_initial)
        self._fh.write("p proof %d\n" % n_initial)

    def log_step(self, new_id, pivot, id1, id2, resolvent):
        """Record one resolution step.

        Args:
            new_id    : ID for the new resolvent clause
            pivot     : pivot literal (id1 has -pivot, id2 has +pivot)
            id1       : parent clause ID containing -pivot
            id2       : parent clause ID containing +pivot
            resolvent : list[int] forming the resolvent ([] means empty clause)
        """
        # Serialize resolvent: space-separated literals ending with 0 (DIMACS)
        # Empty resolvent [] encodes the empty clause -> just "0"
        if resolvent:
            lits_str = ' '.join(str(l) for l in resolvent) + ' 0'
        else:
            lits_str = '0'
        self._fh.write("%d %d %d %d : %s\n" % (new_id, pivot, id1, id2, lits_str))

    def close(self):
        self._fh.flush()
        self._fh.close()


class _NullLogger:
    """No-op proof logger used when proof output is disabled.
    Zero-cost sentinel so the main logic needs no if-branches.
    """
    def log_step(self, *args, **kwargs):
        pass
    def close(self):
        pass


