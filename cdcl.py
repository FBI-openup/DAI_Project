logger = logging.getLogger(__name__)


class ProofLogger:
    """
    负责将分步归结过程记录到文件。
    记录格式: <new_id> <pivot> <id1> <id2> : <literals...> 0
    """
    def __init__(self, proof_file, n_initial):
        self._fh = open(proof_file, 'w', encoding='utf-8')
        # 写入注释头和维度信息
        self._fh.write("c Resolution proof generated by CDCL solver\n")
        self._fh.write("c Initial clause IDs: 1..%d\n" % n_initial)
        self._fh.write("p proof %d\n" % n_initial)

    def log_step(self, new_id, pivot, id1, id2, resolvent):
        """
        记录一步归结：new_id 是生成的子句ID，pivot 是消解文字，id1/id2 是父子句ID。
        """
        if resolvent:
            lits_str = ' '.join(str(l) for l in resolvent) + ' 0'
        else:
            lits_str = '0' # 空子句
        self._fh.write("%d %d %d %d : %s\n" % (new_id, pivot, id1, id2, lits_str))

    def close(self):
        self._fh.flush()
        self._fh.close()


class _NullLogger:
    """
    空日志器：当不需要生成证明时使用，避免在主循环中进行 if 判断，提高效率。
    """
    def log_step(self, *args, **kwargs):
        pass
    def close(self):
        pass


class CDCL:
    """ Assume the input is as follows:

    A list of clauses, each clause is a list of literals, each literal an integer, either positive or negative.

    All variables are named 1..n, a positive number is a positive literal, a negative number is a negative literal.
    """

    def __init__(self, clauses, proof_file=None):
        self.num_vars = 0
        for c in clauses:
            for i in c:
                if abs(i) > self.num_vars:
                    self.num_vars = abs(i)

        self.clauses = ClauseDb(self.num_vars, clauses)

        # Store the trail of assignments
        # Each element should be (lit, reason, level)
        self.trail = []

        # Current decision level
        self.decision_level = 0

        # Map of current VARIABLE assignment: {var: bool}
        self.assignments = {}

        # 初始化证明日志器
        n_initial = len(self.clauses.clauses)
        if proof_file is not None:
            self.proof = ProofLogger(proof_file, n_initial)
        else:
            self.proof = _NullLogger()


    def solve(self):
        """
        Main CDCL loop. 核心循环：Deduce -> Decide -> Analyze/Backtrack
        """
        logging.info("CDCL Search started")
        while (True):
            conflicting_clause = self.deduce()
            
            if conflicting_clause is None:
                # 无冲突：检查是否所有变量都已赋值
                if (self.all_assigned()):
                    logging.info("All literals assigned, SAT")
                    return True
                else:
                    # 还有未赋值变量：进行决策 (Decision)
                    self.decide()
            else:
                # 冲突检测：如果在决策层 0 发生冲突，说明公式 UNSAT
                if self.decision_level == 0:
                    conflict_id = self.clauses.clause_id.get(
                        id(conflicting_clause),
                        self._clause_id(conflicting_clause)
                    )
                    # 在退出前，补全到“空子句”的归结链
                    self._finish_proof_to_empty(conflicting_clause, conflict_id)
                    return False

                # 冲突分析：计算回溯层级和学习子句
                level, learned_clause = self.analyze(conflicting_clause)
                
                # 执行非时间顺序回溯
                self.backtrack(level)
                # 学习新子句并进入 BCP
                self.learn(learned_clause)

    def is_unit_clause(self, clause):
        """
        判断子句状态：已满足、单位子句、冲突或普通。
        """
        unassigned = []
        
        for lit in clause:
            var = abs(lit)
            if var in self.assignments: 
                var_value = self.assignments[var]
                lit_value = var_value if lit > 0 else not var_value
                if lit_value:  
                    return ("satisfied", None) # 子句已为真
            else:  
                unassigned.append(lit)
        
        if len(unassigned) == 0:
            return ("conflict", None) # 所有文字为假，冲突
        elif len(unassigned) == 1:
            return ("unit", unassigned[0]) # 只有一个文字未定，单位子句
        else:
            return ("normal", None) # 多个文字未定

