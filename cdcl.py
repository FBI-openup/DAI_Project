    def backtrack(self, level):
        """
        回溯到指定层级，撤销该层级之上的所有赋值。
        """
        while len(self.trail) > 0:
            lit, reason, dec_level = self.trail[-1]
            if dec_level <= level:
                break
            var = abs(lit)
            del self.assignments[var]
            self.trail.pop()
        self.decision_level = level

