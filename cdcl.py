    def analyze(self, conflicting_clause):
        """
        Analyze the conflicting_clause using the trail.

        Returns the new level to backtrack to and a conflict clause.

        Project 1 Extension
        -------------------
        Every resolution step in the 1st-UIP derivation is logged via
        self.proof.log_step() (factored through _proof_resolve_step).

        Two special cases that need extra proof work:

        (A) decision_level == 0 from the start:
            All trail entries are BCP-forced (reason != None).
            We resolve the conflicting clause down to empty directly.

        (B) 1st-UIP produces a clause with only level-1 or higher literals,
            backtrack_level == 0, but the conflict is not yet empty.
            We run a second backward pass over the full trail to reduce
            the remaining literals to the empty clause.

        Both cases are handled by _finish_proof_to_empty() called after
        the normal 1st-UIP loop when we know we are returning (0, ...).
        """
        logging.info("Conflict analysis")
        
        # Note: decision_level == 0 case is now handled directly in solve() before
        # calling analyze(), so we should never reach here at level 0.
        # If we do (defensive), just return (0, conflicting_clause) with no proof step.
        if self.decision_level == 0:
            return 0, conflicting_clause
        
        # Build literal -> decision_level mapping in one trail pass
        lit_to_level = {}
        for trail_lit, reason, level in self.trail:
            lit_to_level[trail_lit]  = level
            lit_to_level[-trail_lit] = level
        
        # -- Proof: track the current working clause's ID ---------------------
        # Prefer object-identity lookup (deduce returns the exact list object)
        # then fall back to content-based lookup.
        current_id = self.clauses.clause_id.get(
            id(conflicting_clause),
            self._clause_id(conflicting_clause)
        )

        conflict = list(conflicting_clause)
        
        # Count literals at current decision level
        current_level_count = sum(1 for lit in conflict 
                                 if lit_to_level.get(lit, 0) == self.decision_level)
        
        # Backward traversal for 1st-UIP resolution
        # Stop when exactly one literal at the current decision level remains.
        i = len(self.trail) - 1
        while current_level_count > 1:
            lit, reason, level = self.trail[i]
            
            if -lit in conflict and reason is not None:
                conflict, current_id = self._proof_resolve_step(
                    conflict, current_id, lit, reason
                )
                # Recount literals at current level
                current_level_count = sum(1 for l in conflict 
                                         if lit_to_level.get(l, 0) == self.decision_level)
            
            i -= 1
        
        # Calculate backtrack level (second highest decision level in conflict)
        levels = [lit_to_level.get(lit, 0) for lit in conflict]
        levels.sort(reverse=True)
        backtrack_level = levels[1] if len(levels) > 1 else 0
        
        logging.info("Learned clause: %s, backtrack to level %d" % (conflict, backtrack_level))

        # When backtrack_level == 0 the proof empty-clause derivation happens
        # in solve() after BCP at level 0 produces a new all-BCP-trail conflict.
        # Nothing needed here.

        return backtrack_level, conflict

    def _finish_proof_to_empty(self, conflict, current_id):
        """Resolve all remaining literals in conflict to derive the empty clause.

        Used for UNSAT termination (backtrack_level == 0).  At this point
        the solver is about to return False, but the proof file needs a
        final step producing the empty clause.

        The literals in conflict were forced by BCP (reason != None) or
        by a decision later negated by a learned clause.  We scan the
        trail backward and resolve every literal we can.

        This function MODIFIES the clause database (adds intermediate IDs)
        but does NOT modify self.trail or self.assignments.

        Note: for decision literals (reason is None) the negation must come
        from an initial or learned unit clause.  We scan clauses for it.
        """
        working    = list(conflict)
        working_id = current_id

        # Build a quick-lookup map: literal -> reason clause for BCP entries
        # (only entries with a reason; decision entries have reason=None)
        lit_to_reason = {}
        for trail_lit, reason, level in self.trail:
            if reason is not None:
                # trail_lit is True, so its negation (-trail_lit) is False.
                # If conflict contains -trail_lit, we can resolve using reason.
                lit_to_reason[-trail_lit] = reason

        # Keep resolving until empty clause or no more progress
        changed = True
        while working and changed:
            changed = False
            i = 0
            while i < len(working):
                lit = working[i]
                reason = lit_to_reason.get(lit)
                if reason is not None:
                    # pivot = -lit (the trail assigned -lit as True, so reason has -lit)
                    # Actually: trail has trail_lit = -lit (True), reason clause forces -lit.
                    # resolve(conflict, reason, pivot) where pivot = -lit:
                    #   conflict has +lit (= -(-lit)), reason has -lit.
                    # Wait - let us be precise:
                    #   lit   is in working (False in current assignment)
                    #   -lit  is True (assigned by BCP from reason clause)
                    #   reason clause contains -lit among its literals
                    #   To resolve: pivot = -lit
                    #     id1 = working_id  (contains +(-lit) = lit? No...)
                    # Re-check sign convention in resolve():
                    #   resolve(clause1, clause2, lit):
                    #     clause1 contains -lit, clause2 contains +lit
                    # So for our case:
                    #   pivot_lit = -lit  (what the trail assigned as true)
                    #   clause1 (working) contains +pivot_lit? No, working has lit = -pivot_lit
                    #   clause2 (reason) should contain -pivot_lit? ...
                    #
                    # Let us re-derive carefully:
                    #   working contains the literal `lit` (which is False).
                    #   The trail contains trail entry (-(-lit) = ?)  -> trail has -lit absent
                    #   Actually: lit is False means trail assigned -lit := True.
                    #   trail_lit = -lit is True.
                    #   reason clause drove unit propagation of -lit (True).
                    #   reason contains -lit (the propagated literal).
                    #
                    #   Resolution on pivot p:
                    #     Remove  p from clause containing  p
                    #     Remove -p from clause containing -p
                    #     Union the rest.
                    #
                    #   pivot = lit  (working has -lit? No, working has +lit=lit)
                    #   Hmm: working contains `lit`.  We want to eliminate `lit`.
                    #   Resolution on pivot=lit eliminates lit from id1 and -lit from id2.
                    #   clause1 (id1) must contain -pivot = -lit   -> NO, working has +lit
                    #   clause2 (id2) must contain  pivot =  lit   -> working has lit, ok
                    #
                    #   Swap: pivot = -lit
                    #   clause1 must contain -(-lit) = lit  -> working has lit, OK
                    #   clause2 must contain  (-lit)        -> reason has -lit, OK
                    #
                    # Therefore: pivot = -lit, id1 = working, id2 = reason
                    pivot = -lit   # the literal to resolve away
                    working, working_id = self._proof_resolve_step(
                        working, working_id, pivot, reason
                    )
                    changed = True
                    i = 0   # restart from beginning
                else:
                    i += 1

