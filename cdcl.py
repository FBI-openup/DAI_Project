    def decide(self):
        """
        Select a new unassigned literal.

        Must update the trail, variable assignments, and decision level accordingly.
        """
        logging.info("Decide a new variable assignment")
        
        self.decision_level += 1
        
        # find a lit unassigned
        for var in range(1, self.num_vars + 1):
            if var not in self.assignments:
                lit = var  #decide positive literal = true
                
                logging.info("Decision: variable %d = True at level %d" % (var, self.decision_level))
                
                # update assignments and trail
                self.assignments[var] = True
                self.trail.append((lit, None, self.decision_level))  # reason=None means decided
                return
        # A secure print
        logging.warning("decide() called but all variables assigned,check solve() should have all assigned check")
    
    def resolve(self, clause1, clause2, lit):
        """
        Resolute 2 clauses
        clause1 contains -lit, clause2 contains lit
        return resoluted clause
        """
        result = []
        
        # add all literals from clause1 except -lit
        for l in clause1:
            if l != -lit:
                result.append(l)
        
        # add all literals from clause2 except lit (remove duplicates)
        for l in clause2:
            if l != lit and l not in result:
                result.append(l)
        
        return result

    def _clause_id(self, clause_list):
        """Look up proof ID of a clause by content (sorted-tuple key).
        Fallback to 0 if not registered.
        """
        key = tuple(sorted(clause_list))
        return self.clauses.content_to_id.get(key, 0)

    def _proof_resolve_step(self, conflict, current_id, lit, reason):
        """Helper: log one proof step and return (new_clause, new_id).

        Encapsulates the three actions that always go together:
          1. Determine parent IDs
          2. Log the step
          3. Register the new clause
          4. Return updated (conflict, id)

        This helper is called both from the 1st-UIP loop and from the
        extra pass that reduces the conflict to the empty clause.
        Every resolution step in the proof goes through here so the
        logic is in one place and easy to inspect.

        Parameters
        ----------
        conflict    : current working clause (list[int]) that contains -lit
        current_id  : proof ID of conflict
        lit         : pivot literal (reason contains +lit, conflict contains -lit)
        reason      : reason clause (list[int]) containing +lit
        """
        reason_id  = self._clause_id(reason)
        new_id     = self.clauses.next_id
        self.clauses.next_id += 1

        # pivot = lit: id1=current_id has -lit, id2=reason_id has +lit
        new_clause = self.resolve(conflict, reason, lit)

        self.proof.log_step(
            new_id    = new_id,
            pivot     = lit,
            id1       = current_id,
            id2       = reason_id,
            resolvent = new_clause,
        )

        # Register new clause in content map so later steps can look it up
        self.clauses.content_to_id[tuple(sorted(new_clause))] = new_id
        return new_clause, new_id

