    def learn(self, clause):
        """
        Add a new clause to the set of clauses.

        Does not return a value.

        Project 1 Extension:
            We register the new clause in clause_id by object identity
            so deduce() can look it up later when the clause triggers a conflict.
        """
        logging.info("Learning a new clause: %s" % clause)

        # Register by object identity: deduce() returns the list object,
        # and we need to map id(list) -> proof_id for future conflict analysis.
        key    = tuple(sorted(clause))
        pid    = self.clauses.content_to_id.get(key, 0)
        self.clauses.clause_id[id(clause)] = pid

        # MODIFIED: self.clauses is ClauseDb object, need to access .clauses list
        self.clauses.clauses.append(clause)


